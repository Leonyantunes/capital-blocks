/** faixas para o gradiente didático */
export const WAGE_BUCKETS = [
  { max: 300, color: '#f44336', label: '< US$ 300/mês' },
  { max: 700, color: '#ff8a65', label: 'US$ 300–700' },
  { max: 1500, color: '#ffc107', label: 'US$ 700–1.500' },
  { max: 3000, color: '#42a5f5', label: 'US$ 1.500–3.000' },
  { max: Infinity, color: '#26a69a', label: '> US$ 3.000' },
]

export function wageColor(usd: number): string {
  return WAGE_BUCKETS.find((b) => usd <= b.max)?.color ?? '#26a69a'
}

export function wageBucketLabel(usd: number): string {
  const b = WAGE_BUCKETS.find((x) => usd <= x.max)
  return b ? b.label : '> US$ 3.000'
}
